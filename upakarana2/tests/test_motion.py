"""test_motion.py — verb semantics infrastructure: motion verbs, verb-concept chains,
auxiliary composites, and construction-level bindings.

Four layers of capability, all xfail until built:
  L1  verb-concept chain   — verb base form lands on a kosha concept, not dhatu loop
  L2  participle wiring    — -ing forms connected to dhatu system (swarupa→tinanta, janya→dhatu)
  L3  auxiliary composite   — "is moving" = single semantic verb unit (aux + participle)
  L4  verb-rate binding    — "V at X unit" binds X to the rate-concept of the verb
"""

import pytest

xfail = pytest.mark.xfail


# ══════════════════════════════════════════════════════════════════════════════
# Layer 1: verb-concept chain — verb base form → kosha concept
# ══════════════════════════════════════════════════════════════════════════════
# "accelerate" → acceleration works because word-node("accelerate") → acceleration.
# "move" → dhatu-move LOOPS. The verb-concept chain in emit-triples breaks
# when word-node(base) == dhatu (the neq guard filters it out).
# Fix: each physics verb needs a kosha concept to land on.


def test_L1_move_verb_concept(vy):
    """'moves' should extract displacement concept via verb-concept chain"""
    g = vy.bqg("a ball moves")
    satya = vy.subjects(g, pred="satya")
    assert "displacement" in satya, f"expected displacement in satya, got {satya}"


