@xfail(strict=True, reason="auxiliary-composite: 'is accelerating at' binds unit not concept without composite")
def test_L3_is_accelerating_composite(vy):
    """'is accelerating at 3' — composite should bind like 'accelerates at 3'"""
    g = vy.bqg("a car is accelerating at 3 m/s2")
    sankhya = vy.triple_map(g, pred="sankhya")
    # "accelerates at" works via verb-concept. "is accelerating at" currently
    # binds to acceleration too (lucky: verb-concept chain works for accelerate).
    # But the composite should produce a SINGLE verb context, not copula + verb.
    # Test that the copula doesn't produce a spurious kaala triple on "car".
    copula_triples = [t for t in g if isinstance(t, list) and t[1] == "copula"]
    assert len(copula_triples) == 0, \
        f"composite 'is accelerating' should not leave orphan copula: {copula_triples}"


