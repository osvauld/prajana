# ══════════════════════════════════════════════════════════════════════════════
# Layer 2: participle wiring — -ing forms in dhatu system
# ══════════════════════════════════════════════════════════════════════════════
# verb-moving and verb-rotating are legacy orphans: no swarupa→tinanta,
# no janya→dhatu-X. All other -ing forms (running, accelerating, etc.) are
# properly generated by kriya-nirmana. These two need fixing.


def test_L2_moving_is_tinanta(vy):
    """'moving' should be classified as tinanta (verb form)"""
    nd = vy.eval('(word-node "moving")')
    swarupa = vy.walk(nd, "swarupa")
    assert "tinanta" in swarupa, f"'moving' node {nd} missing swarupa→tinanta"


def test_L2_moving_janya_dhatu(vy):
    """'moving' should have janya edge back to dhatu-move"""
    nd = vy.eval('(word-node "moving")')
    janya = vy.walk(nd, "janya")
    assert "dhatu-move" in janya, f"'moving' node {nd} missing janya→dhatu-move"


def test_L2_rotating_is_tinanta(vy):
    """'rotating' should be classified as tinanta"""
    nd = vy.eval('(word-node "rotating")')
    swarupa = vy.walk(nd, "swarupa")
    assert "tinanta" in swarupa, f"'rotating' node {nd} missing swarupa→tinanta"


def test_L2_moving_emits_tense(vy):
    """'moving' should emit vartamana-kaala tense, like 'running' does"""
    g = vy.bqg("the ball is moving")
    # 'running' correctly emits vartamana-kaala; 'moving' should too
    assert vy.has_triple(g, subj="moving", pred="vartamana-kaala") or \
        vy.has_triple(g, pred="vartamana-kaala")


# ══════════════════════════════════════════════════════════════════════════════
# Layer 3: auxiliary composites — "is moving" = single verb unit
# ══════════════════════════════════════════════════════════════════════════════
# BQG processes word-by-word. "is" → copula, "moving" → separate token.
# The composite "is moving" should be recognised as present continuous,
# "was moving" as past continuous (→ initial state via kaala-avastha).


@xfail(strict=True, reason="auxiliary-composite: 'is moving' not recognised as present continuous verb")
def test_L3_is_moving_composite(vy):
    """'is moving at 5' — auxiliary+participle should act as single verb"""
    g = vy.bqg("a ball is moving at 5 m/s")
    sankhya = vy.triple_map(g, pred="sankhya")
    # must bind to velocity concept, not just the unit node
    assert "velocity" in sankhya, f"expected velocity in sankhya, got {sankhya}"


@xfail(strict=True, reason="auxiliary-composite: 'was moving' should signal past state via kaala-avastha")
def test_L3_was_moving_initial_state(vy):
    """'was moving at 5' — past continuous → initial-velocity via kaala-avastha"""
    g = vy.bqg("the ball was moving at 5 m/s")
    sankhya = vy.triple_map(g, pred="sankhya")
    # must bind to velocity concept (or initial-velocity), not just unit
    assert "initial-velocity" in sankhya or "velocity" in sankhya, \
        f"expected velocity concept in sankhya, got {sankhya}"


